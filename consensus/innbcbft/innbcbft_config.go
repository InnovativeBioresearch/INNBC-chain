func ParseRawTokenConfig(rawConfig string) (*TokenConfig, error) {
	if rawConfig == "" {
		return DefaultTokenConfig, nil
	}

	params := strings.Split(rawConfig, ":")
	/* START ALPHA CHANGE 778 -- reject obsolete native token mintable flag parameter -- */
	if len(params) != minNativeTokenParamsNumber {
		return nil, errInvalidTokenParams
	}
	/* FINISH ALPHA CHANGE 778 -- reject obsolete native token mintable flag parameter -- */

	// name
	name := strings.TrimSpace(params[0])
	if name == "" {
		return nil, errInvalidTokenParams
	}

	// symbol
	symbol := strings.TrimSpace(params[1])
	if symbol == "" {
		return nil, errInvalidTokenParams
	}

	// decimals
	decimals, err := strconv.ParseUint(strings.TrimSpace(params[2]), 10, 8)
	if err != nil || decimals > math.MaxUint8 {
		return nil, errInvalidTokenParams
	}

	/* START ALPHA CHANGE 779 -- remove legacy native token mintable flag parsing -- */
	/* FINISH ALPHA CHANGE 779 -- remove legacy native token mintable flag parsing -- */

	return &TokenConfig{
		Name:     name,
		Symbol:   symbol,
		Decimals: uint8(decimals),
	}, nil
}

