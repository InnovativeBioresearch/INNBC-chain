// LoadINNBCBFTConfig loads chain config from provided path and unmarshals INNBCBFTConfig
func LoadINNBCBFTConfig(chainConfigFile string) (INNBCBFTConfig, error) {
	chainCfg, err := chain.ImportFromFile(chainConfigFile)
	if err != nil {
		return INNBCBFTConfig{}, err
	}

	innbcbftConfig, err := GetINNBCBFTConfig(chainCfg)
	if err != nil {
		return INNBCBFTConfig{}, err
	}

	return innbcbftConfig, err
}

// GetINNBCBFTConfig deserializes provided chain config and returns INNBCBFTConfig
/* START ALPHA CHANGE 2638 -- validate genesis stake when decoding chain configuration -- */

func GetINNBCBFTConfig(chainConfig *chain.Chain) (INNBCBFTConfig, error) {
	if chainConfig == nil || chainConfig.Params == nil {
		return INNBCBFTConfig{}, errors.New("missing INNBC chain parameters")
	}

	consensusConfigJSON, err := json.Marshal(chainConfig.Params.Engine[ConsensusName])
	if err != nil {
		return INNBCBFTConfig{}, err
	}

	var innbcBFTConfig INNBCBFTConfig
	if err = json.Unmarshal(consensusConfigJSON, &innbcBFTConfig); err != nil {
		return INNBCBFTConfig{}, err
	}

	if err := innbcBFTConfig.ValidatorRegistryConfig.validateGenesisMinimumStake(); err != nil {
		return INNBCBFTConfig{}, err
	}

	/* START ALPHA CHANGE 3316 -- validate programmatic and decoded chain-clock configuration -- */
	if err := chainConfig.ValidateChainClock(); err != nil {
		return INNBCBFTConfig{}, err
	}
	/* FINISH ALPHA CHANGE 3316 -- validate programmatic and decoded chain-clock configuration -- */

	/* START ALPHA CHANGE 3337 -- reject missing native-token configuration at the shared decoding boundary -- */
	if err := ValidateNativeTokenConfig(innbcBFTConfig.NativeTokenConfig); err != nil {
		return INNBCBFTConfig{}, err
	}
	/* FINISH ALPHA CHANGE 3337 -- reject missing native-token configuration at the shared decoding boundary -- */

	/* START ALPHA CHANGE 3438 -- reject unsupported epoch sizes at the shared configuration boundary -- */
	if err := ValidateEpochSize(innbcBFTConfig.EpochSize); err != nil {
		return INNBCBFTConfig{}, err
	}
	/* FINISH ALPHA CHANGE 3438 -- reject unsupported epoch sizes at the shared configuration boundary -- */

	return innbcBFTConfig, nil
}

