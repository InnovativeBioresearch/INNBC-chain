/* START ALPHA CHANGE 92 -- map INNBC validator registry preset names to Solidity enum values -- */
func ParseValidatorRegistryProposalDurationPreset(preset string) (uint8, error) {
	switch strings.ToLower(strings.TrimSpace(preset)) {
	case ValidatorRegistryProposalDurationShort:
		return ValidatorRegistryProposalDurationShortValue, nil
	case ValidatorRegistryProposalDurationStandard:
		return ValidatorRegistryProposalDurationStandardValue, nil
	case ValidatorRegistryProposalDurationLong:
		return ValidatorRegistryProposalDurationLongValue, nil
	default:
		return ValidatorRegistryProposalDurationNoneValue, errInvalidValidatorRegistryProposalDurationPreset
	}
}

